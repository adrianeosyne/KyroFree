export interface ApiEndpoint {
  id: string;
  method: string;
  path: string;
  description: string;
  permission: string;
  body: Record<string, unknown> | null;
  response: unknown;
  query: string;
  notes?: string;
}
function endpoint(
  id: string,
  method: string,
  path: string,
  description: string,
  permission = "Authenticated bot",
  body: Record<string, unknown> | null = null,
  response: unknown = { id: "RESOURCE_ID" },
  query = "",
  notes = "",
): ApiEndpoint {
  return {
    id,
    method,
    path,
    description,
    permission,
    body,
    response,
    query,
    notes,
  };
}
