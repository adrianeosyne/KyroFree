export function matchApiEndpoint(method: string, path: string) {
  return API_ENDPOINTS.find(
    (e) =>
      e.method === method &&
      new RegExp(
        "^" +
          e.path
            .split("/")
            .map((p) => (p.startsWith(":") ? "[a-zA-Z0-9_-]+" : p))
            .join("/") +
          "$",
      ).test(path),
  );
}
